export function huntCsv027(rows: readonly HuntRow027[]): string {
  const header = [
    "SOURCE",
    "URL",
    "WHAT_FOUND",
    "DOWNLOADABLE",
    "FORMAT",
    "TIMESTAMP",
    "KICKOFF",
    "MATCHABLE",
    "EVENT_COUNT",
    "STRICT_COUNT",
    "LICENSE_STATUS",
    "CLASS",
  ];
  const lines = [header.join(",")];
  for (const r of rows) {
    const cells = [
      r.source,
      r.url,
      r.what_found,
      String(r.downloadable),
      r.format,
      r.timestamp,
      r.kickoff,
      r.matchable,
      r.event_count == null ? "" : String(r.event_count),
      r.strict_count == null ? "" : String(r.strict_count),
      r.license_status,
      r.class,
    ].map(csvCell);
    lines.push(cells.join(","));
  }
  return lines.join("\n") + "\n";
}

function csvCell(s: string): string {
  const t = s.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, " ");
  return /[",\n]/.test(t) ? `"${t.replace(/"/g, '""')}"` : t;
}
