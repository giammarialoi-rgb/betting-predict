export function writeTask036Artifacts(report: Task036Report): void {
  const artifacts = join(process.cwd(), "artifacts");
  const dir = join(artifacts, "task-036");
  const docs = join(process.cwd(), "docs");
  mkdirSync(dir, { recursive: true });
  mkdirSync(docs, { recursive: true });
  writeFileSync(join(artifacts, "task-036-result.json"), JSON.stringify(report, null, 2));
  writeFileSync(join(dir, "health.json"), JSON.stringify(report.health, null, 2));
  writeFileSync(join(dir, "manifest.json"), JSON.stringify({
    experiment_id: report.experiment_id,
    verdict: report.verdict,
    winner: report.winner,
    fingerprint: report.fingerprint,
    reproducibility: report.reproducibility,
  }, null, 2));
  writeFileSync(join(docs, "task-036-final-report.md"), renderFinalReport036(report));
  writeFileSync(join(docs, "task-036-prospective-architecture.md"), renderArchitecture036());
  writeFileSync(join(docs, "task-036-temporal-protocol.md"), renderTemporal036());
  writeFileSync(join(docs, "task-036-source-audit.md"), renderSourceAudit036(report));
  writeFileSync(join(docs, "task-036-data-lineage.md"), renderLineage036(report));
  writeFileSync(join(docs, "task-036-collection-runbook.md"), renderRunbook036());
}
