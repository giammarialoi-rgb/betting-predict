function classFrom037(classification: string): TemporalClass038 {
  if (classification === "DATE_ONLY") return "DATE_ONLY";
  if (classification === "RESEARCH_TEMPORAL") return "RESEARCH_TEMPORAL";
  if (classification === "POSTMATCH") return "POSTMATCH";
  if (classification === "NAIVE_DATETIME") return "AMBIGUOUS";
  return "INVALID";
}

export function loadHarvest037Snapshot(): RepoHarvest037[] {
  const p = join(process.cwd(), "artifacts", "task-037-result.json");
  if (existsSync(p)) {
    try {
      const raw = JSON.parse(readFileSync(p, "utf8")) as { harvest?: RepoHarvest037[] };
      if (Array.isArray(raw.harvest) && raw.harvest.length) return raw.harvest;
    } catch {
      /* fall through */
    }
  }
  return harvestGithub037({ skipHeavy: true });
}

