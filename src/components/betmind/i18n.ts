const catalogs: Record<BmLocale, BmMessages> = { it, en };

export function getBmMessages(locale: BmLocale = DEFAULT_BM_LOCALE): BmMessages {
  return catalogs[locale] ?? catalogs.it;
}

/** Client helper — default Italian. Optional `localStorage.bm_locale`. */
export function resolveBmLocale(): BmLocale {
  if (typeof window === "undefined") return DEFAULT_BM_LOCALE;
  try {
    const stored = window.localStorage.getItem("bm_locale");
    if (stored === "en" || stored === "it") return stored;
  } catch {
    /* ignore */
  }
  return DEFAULT_BM_LOCALE;
}
